import { BadgeCheck, Cog } from "lucide-react";
import { segmentFigures } from "../lib/explain";
import type { Explanation } from "../lib/types";
import { cx } from "./ui";

export function ExplanationCard({ explanation, pending }: { explanation: Explanation | null; pending: boolean }) {
  if (pending) {
    return (
      <div className="mb-5" role="status" aria-label="Writing a summary">
        <div className="space-y-2" aria-hidden>
          <div className="h-4 w-11/12 animate-pulse rounded bg-raised" />
          <div className="h-4 w-3/4 animate-pulse rounded bg-raised" />
        </div>
        <p className="mt-2 text-[13px] text-faint">Writing a summary, then checking every figure against the result…</p>
      </div>
    );
  }
  if (!explanation) return null;
  const llm = explanation.source === "llm";
  return (
    <div className="mb-5">
      <p className="text-[17px] leading-relaxed">
        {segmentFigures(explanation.text).map((seg, i) =>
          seg.figure
            ? <span key={i} className="rounded bg-signal/10 px-1 font-mono text-[0.94em] text-text tnum">{seg.text}</span>
            : <span key={i}>{seg.text}</span>,
        )}
      </p>
      <p className={cx("mt-2 inline-flex items-center gap-1.5 text-[13px]", llm ? "text-verified" : "text-faint")}
         title={llm
           ? "Each number in this summary was matched to the result, or to simple arithmetic on it (a total, a difference, a percentage change)."
           : "This summary was generated by fixed rules from the result, so it cannot contain an invented figure."}>
        {llm ? <BadgeCheck size={15} /> : <Cog size={14} />}
        {llm
          ? `Written by the model. ${explanation.numbers_checked} figure${explanation.numbers_checked === 1 ? "" : "s"} checked against the result${explanation.retried ? " (corrected once)" : ""}.`
          : explanation.retried
            ? "Rule-based summary: the model's version contained a figure that is not in the data."
            : "Rule-based summary (no model involved)."}
      </p>
    </div>
  );
}
