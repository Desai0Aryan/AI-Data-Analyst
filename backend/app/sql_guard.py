"""SQL safety layer.

Every query that reaches the database, whether written by a user or generated by an LLM,
passes through ``validate_sql`` first. It uses SQLGlot to parse the statement into an
AST and then *allow-lists* what is permitted instead of trying to deny-list bad strings.

Checks, in order:
  1. Exactly one statement, and it must parse (Postgres dialect).
  2. The root must be a read-only query (SELECT / UNION / INTERSECT / EXCEPT).
  3. No DML/DDL/admin nodes anywhere in the tree. This catches data-modifying CTEs
     such as ``WITH d AS (DELETE ... RETURNING *) SELECT * FROM d``.
  4. No SELECT ... INTO and no row locks (FOR UPDATE).
  5. No dangerous functions (pg_sleep, pg_read_file, dblink, set_config, ...).
  6. Only tables from the schema allow-list may be referenced (blocks pg_catalog,
     information_schema, other schemas).
  7. A row LIMIT is always enforced.

The SQL that is executed is the *regenerated* SQL from the AST, not the raw input,
which also removes comments and odd formatting tricks.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

import sqlglot
from sqlglot import exp
from sqlglot.errors import SqlglotError

DIALECT = "postgres"

# Node types that must never appear anywhere in the tree.
_FORBIDDEN_NODES: tuple[type[exp.Expression], ...] = tuple(
    getattr(exp, name)
    for name in (
        "Insert", "Update", "Delete", "Merge", "Create", "Drop", "Alter",
        "AlterTable", "TruncateTable", "Copy", "Command", "Set", "Use", "Grant",
        "Revoke", "Transaction", "Commit", "Rollback", "Analyze", "Pragma",
        "LoadData", "Kill", "Execute", "Declare", "Refresh", "Comment",
    )
    if hasattr(exp, name)
)

_ALLOWED_ROOTS = (exp.Select, exp.Union, exp.Intersect, exp.Except)

# Exact function names that are blocked.
_BLOCKED_FUNCTIONS = frozenset({
    "pg_sleep", "pg_sleep_for", "pg_sleep_until",
    "set_config", "current_setting",
    "lo_import", "lo_export", "lo_open", "lo_get", "lo_put",
    "dblink", "dblink_exec", "dblink_connect",
    "query_to_xml", "table_to_xml", "database_to_xml", "cursor_to_xml",
    "version", "current_version", "current_database", "current_schemas",
    "inet_server_addr", "inet_client_addr",
})
# Any function starting with one of these prefixes is blocked.
_BLOCKED_FUNCTION_PREFIXES = ("pg_", "lo_", "dblink", "txid_", "xmlforest_")


class SQLGuardError(Exception):
    """Raised when SQL is rejected. ``code`` is machine-readable; ``message`` is
    written so it can be fed straight back to an LLM in the repair loop (Part 2)."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


@dataclass
class GuardResult:
    sql: str                      # normalized, safe-to-execute SQL (with LIMIT)
    tables: list[str]             # base tables referenced
    effective_limit: int          # LIMIT that will be applied
    limit_applied: bool           # True if we added or lowered the LIMIT
    warnings: list[str] = field(default_factory=list)


_RENDERED_NAME = re.compile(r"^\s*\"?([A-Za-z_][A-Za-z0-9_$.]*)\"?\s*\(")


def _function_names(node: exp.Func) -> set[str]:
    """Every name a function call could be known by.

    sqlglot sometimes models a Postgres function as its own node type (``version()``
    becomes ``CurrentVersion``), so we check both the AST name and the name as it
    appears in the SQL that would actually be sent to Postgres.
    """
    names = set()
    if isinstance(node, exp.Anonymous):
        names.add(str(node.name).lower())
    else:
        names.add(node.sql_name().lower())
    match = _RENDERED_NAME.match(node.sql(dialect=DIALECT))
    if match:
        names.add(match.group(1).lower().split(".")[-1])
    return names


def _enforce_limit(tree: exp.Expression, max_rows: int) -> tuple[int, bool]:
    """Ensure the outermost query has LIMIT <= max_rows. Returns (limit, changed)."""
    existing = tree.args.get("limit")
    if isinstance(existing, exp.Limit):
        value = existing.expression
        if isinstance(value, exp.Literal) and value.is_int:
            n = int(value.this)
            if n <= max_rows:
                return n, False
    # Missing, too large, non-literal (e.g. LIMIT ALL / FETCH ...): replace it.
    tree.set("limit", None)
    tree.limit(max_rows, copy=False)
    return max_rows, True


def validate_sql(sql: str, allowed_tables: set[str], max_rows: int = 1000) -> GuardResult:
    """Validate and normalize ``sql``. Raises SQLGuardError if it is not safe."""
    if not sql or not sql.strip():
        raise SQLGuardError("empty", "The query is empty.")

    # 1. Parse: exactly one statement.
    try:
        statements = [s for s in sqlglot.parse(sql, read=DIALECT) if s is not None]
    except SqlglotError as e:
        raise SQLGuardError("syntax", f"SQL syntax error: {_short(e)}") from e
    if not statements:
        raise SQLGuardError("empty", "The query is empty.")
    if len(statements) > 1:
        raise SQLGuardError("multiple_statements", "Only a single SQL statement is allowed.")
    tree = statements[0]

    # 2. Root must be a read-only query.
    if not isinstance(tree, _ALLOWED_ROOTS):
        raise SQLGuardError(
            "not_read_only",
            f"Only SELECT queries are allowed (got {type(tree).__name__.upper()}).",
        )

    # 3. No write/admin nodes anywhere (covers data-modifying CTEs and subqueries).
    for node in tree.walk():
        if isinstance(node, _FORBIDDEN_NODES):
            raise SQLGuardError(
                "forbidden_statement",
                f"{type(node).__name__.upper()} operations are not allowed; the database is read-only.",
            )

    # 4. SELECT INTO / locking reads.
    for select in tree.find_all(exp.Select):
        if select.args.get("into"):
            raise SQLGuardError("forbidden_statement", "SELECT ... INTO is not allowed.")
        if select.args.get("locks"):
            raise SQLGuardError("forbidden_statement", "Row locking (FOR UPDATE/SHARE) is not allowed.")

    # 5. Function deny-list.
    for fn in tree.find_all(exp.Func):
        for name in _function_names(fn):
            if name in _BLOCKED_FUNCTIONS or name.startswith(_BLOCKED_FUNCTION_PREFIXES):
                shown = name.replace("current_version", "version")
                raise SQLGuardError("forbidden_function", f"Function '{shown}' is not allowed.")

    # 6. Table allow-list (CTE names are fine, everything else must be a known table).
    cte_names = {cte.alias_or_name.lower() for cte in tree.find_all(exp.CTE)}
    allowed = {t.lower() for t in allowed_tables}
    referenced: list[str] = []
    for table in tree.find_all(exp.Table):
        name = table.name.lower()
        if not name:
            # e.g. a table-valued function like generate_series(); covered by function checks.
            continue
        schema = table.args.get("db")
        qualified_ok = schema is None or schema.name.lower() == "public"
        if table.args.get("catalog"):
            qualified_ok = False
        if name in cte_names and schema is None:
            continue
        if not qualified_ok or name not in allowed:
            shown = ".".join(p for p in (schema.name if schema else None, table.name) if p)
            raise SQLGuardError(
                "unknown_table",
                f"Table '{shown}' does not exist or is not accessible. "
                f"Available tables: {', '.join(sorted(allowed))}.",
            )
        if name not in referenced:
            referenced.append(name)

    # 7. Row limit.
    limit, changed = _enforce_limit(tree, max_rows)
    warnings = [f"LIMIT {max_rows} was applied automatically."] if changed else []

    return GuardResult(
        sql=tree.sql(dialect=DIALECT, comments=False),
        tables=sorted(referenced),
        effective_limit=limit,
        limit_applied=changed,
        warnings=warnings,
    )


def _short(err: Exception) -> str:
    return str(err).strip().splitlines()[0][:300]
